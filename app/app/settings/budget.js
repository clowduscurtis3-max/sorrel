import { useCallback, useMemo, useState } from 'react';
import { View, Text, Switch, ActivityIndicator, Pressable, Alert, StyleSheet } from 'react-native';
import { useRouter, useFocusEffect } from 'expo-router';
import { MaterialIcons } from '@expo/vector-icons';
import { apiFetch, apiErrorMessage, patchSettings } from '../_lib/api';
import { showDiscretionaryShortfallAlert } from '../_lib/goalFunding';
import { useTheme } from '../_lib/theme';
import SettingsScreenChrome from '../_components/SettingsScreenChrome';
import SettingsFetchGate from '../_components/SettingsFetchGate';

const SECTION = 'budget_settings';

// Phase 38 Step 2. The "start over completely" whole-budget regenerate
// lives only here, not on the Budget tab itself - `generateBudget`'s
// `force` option (server/budget.js, built in Phase 37) was deliberately
// left unwired to any control there per direct user decision, specifically
// so it wouldn't compete with that screen's existing (non-destructive,
// user-set-preserving) "REGENERATE BUDGET" button. That button is
// untouched by this step. The per-category "Reset to AI-suggested" link
// (also Phase 37) is Budget-tab UI and already closed - nothing to do for
// it here either.
//
// Theme redesign (2026-09-11): colors/styles now come from useTheme().
export default function BudgetSettings() {
  const { colors, styles } = useTheme();
  const budgetSettingsStyles = useMemo(() => buildBudgetSettingsStyles(colors), [colors]);
  const router = useRouter();
  const [settings, setSettings] = useState(null);
  const [error, setError] = useState(null);
  const [saving, setSaving] = useState(false);
  const [regenerating, setRegenerating] = useState(false);

  const fetchSettings = useCallback(async () => {
    setError(null);
    try {
      const res = await apiFetch('/settings');
      if (!res.ok) throw new Error('SERVER_ERROR');
      setSettings(await res.json());
    } catch (err) {
      console.error(err);
      setError(apiErrorMessage(err));
    }
  }, []);

  useFocusEffect(
    useCallback(() => {
      fetchSettings();
    }, [fetchSettings])
  );

  async function patchSetting(key, value) {
    setSettings((prev) => ({ ...prev, [SECTION]: { ...prev[SECTION], [key]: value } }));
    setSaving(true);
    setError(null);
    try {
      setSettings(await patchSettings(SECTION, { [key]: value }));
    } catch (err) {
      console.error(err);
      setError(apiErrorMessage(err));
      // Re-fetch real server state on failure rather than restoring a
      // locally-held snapshot (code review, 2026-09-02) - see
      // SettingsSectionShell.js's identical fix for the full reasoning.
      fetchSettings();
    } finally {
      setSaving(false);
    }
  }

  async function regenerateEntireBudget({ allowDiscretionaryBelowFloor = false } = {}) {
    setRegenerating(true);
    setError(null);
    try {
      const res = await apiFetch('/budget/generate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ force: true, allowDiscretionaryBelowFloor }),
      });
      if (!res.ok) {
        if (res.status === 400) {
          const body = await res.json().catch(() => ({}));
          throw new Error(body.error || 'SERVER_ERROR');
        }
        // Real fact, not a failure - see (tabs)/budget.js's identical
        // handling for the full "why" (DiscretionaryFloorShortfallError).
        if (res.status === 409) {
          const body = await res.json().catch(() => ({}));
          if (body.needs_confirmation) {
            showDiscretionaryShortfallAlert(body.error, body.discretionary_categories, () =>
              regenerateEntireBudget({ allowDiscretionaryBelowFloor: true })
            );
            return;
          }
        }
        throw new Error('SERVER_ERROR');
      }
      Alert.alert('Budget regenerated', 'Every category, including any you set manually, was regenerated by the AI from your current spending.');
    } catch (err) {
      console.error(err);
      // Fixed by code review, 2026-09-02: this only special-cased the
      // 'SERVER_ERROR' string thrown a few lines up - a NETWORK_ERROR or
      // SESSION_EXPIRED thrown by apiFetch itself (before the res.ok check
      // above is ever reached) fell through to the `: err.message` branch
      // and displayed that raw internal code verbatim, breaking this app's
      // "advisor, not accountant documents" plain-language voice rule.
      // Only a real server-provided message (the 400 branch above) should
      // ever bypass apiErrorMessage.
      const knownInternalCode = ['SERVER_ERROR', 'NETWORK_ERROR', 'SESSION_EXPIRED'].includes(err.message);
      setError(knownInternalCode ? apiErrorMessage(err) : err.message);
    } finally {
      setRegenerating(false);
    }
  }

  function confirmRegenerateEntireBudget() {
    Alert.alert(
      'Start the budget over completely?',
      "This clears every category - including any you've set manually - and lets the AI regenerate the whole budget from scratch. This can't be undone.",
      [
        { text: 'Cancel', style: 'cancel' },
        { text: 'Regenerate Everything', style: 'destructive', onPress: regenerateEntireBudget },
      ]
    );
  }

  const budgetSettings = settings?.[SECTION] || {};
  const showCategoryReasoning = budgetSettings.show_category_reasoning !== false;
  const showInsightPill = budgetSettings.show_insight_pill !== false;

  return (
    <SettingsScreenChrome title="Budget Settings" onBack={() => router.back()}>
      <SettingsFetchGate loaded={settings !== null} error={error} onRetry={fetchSettings}>
        <View style={budgetSettingsStyles.body}>
          {error && <Text style={styles.errorText}>{error}</Text>}

          <View style={[styles.card, budgetSettingsStyles.card]}>
            <Text style={styles.cardTitle}>Start over completely</Text>
            <Text style={[styles.smallText, budgetSettingsStyles.toggleDescription]}>
              Clears every category, including ones you've set manually, and lets the AI
              regenerate the whole budget from scratch.
            </Text>
            {regenerating ? (
              <ActivityIndicator style={budgetSettingsStyles.regenerateSpacing} />
            ) : (
              <Pressable
                style={[budgetSettingsStyles.destructiveButton, budgetSettingsStyles.regenerateSpacing]}
                onPress={confirmRegenerateEntireBudget}
                accessibilityRole="button"
                accessibilityLabel="Regenerate entire budget"
              >
                <MaterialIcons name="refresh" size={16} color={colors.error} />
                <Text style={budgetSettingsStyles.destructiveButtonText}>REGENERATE ENTIRE BUDGET</Text>
              </Pressable>
            )}
          </View>

          <View style={[styles.card, budgetSettingsStyles.card]}>
            <View style={budgetSettingsStyles.toggleRow}>
              <View style={budgetSettingsStyles.toggleTextCol}>
                <Text style={budgetSettingsStyles.toggleLabel}>Show category reasoning</Text>
                <Text style={[styles.smallText, budgetSettingsStyles.toggleDescription]}>
                  The AI's short note under each budgeted category.
                </Text>
              </View>
              {saving ? (
                <ActivityIndicator />
              ) : (
                <Switch
                  value={showCategoryReasoning}
                  onValueChange={(v) => patchSetting('show_category_reasoning', v)}
                  trackColor={{ false: colors.sage, true: colors.primary }}
                />
              )}
            </View>
            <View style={[budgetSettingsStyles.toggleRow, budgetSettingsStyles.toggleRowDivider]}>
              <View style={budgetSettingsStyles.toggleTextCol}>
                <Text style={budgetSettingsStyles.toggleLabel}>Show Budget Insight pill</Text>
                <Text style={[styles.smallText, budgetSettingsStyles.toggleDescription]}>
                  The "INSIGHTS" shortcut next to the Budget title.
                </Text>
              </View>
              {saving ? (
                <ActivityIndicator />
              ) : (
                <Switch
                  value={showInsightPill}
                  onValueChange={(v) => patchSetting('show_insight_pill', v)}
                  trackColor={{ false: colors.sage, true: colors.primary }}
                />
              )}
            </View>
          </View>
        </View>
      </SettingsFetchGate>
    </SettingsScreenChrome>
  );
}

// Theme redesign (2026-09-11): converted to a builder function, called
// via useMemo inside the component (keyed on colors).
function buildBudgetSettingsStyles(colors) {
  return StyleSheet.create({
    body: {
      flex: 1,
      paddingHorizontal: 16,
      paddingTop: 8,
      gap: 12,
    },
    card: {
      gap: 8,
    },
    regenerateSpacing: {
      marginTop: 4,
    },
    destructiveButton: {
      flexDirection: 'row',
      alignItems: 'center',
      justifyContent: 'center',
      gap: 6,
      borderWidth: StyleSheet.hairlineWidth,
      borderColor: colors.error,
      backgroundColor: colors.background,
      borderRadius: 22,
      paddingVertical: 10,
      minHeight: 40,
    },
    destructiveButtonText: {
      fontSize: 12,
      fontWeight: '700',
      color: colors.error,
      letterSpacing: 0.3,
    },
    toggleRow: {
      flexDirection: 'row',
      alignItems: 'center',
      justifyContent: 'space-between',
      gap: 12,
      paddingVertical: 6,
    },
    toggleRowDivider: {
      borderTopWidth: StyleSheet.hairlineWidth,
      borderTopColor: colors.sage,
      marginTop: 4,
      paddingTop: 12,
    },
    toggleTextCol: {
      flex: 1,
      gap: 2,
    },
    toggleLabel: {
      fontSize: 14,
      fontWeight: '600',
      color: colors.darkest,
    },
    toggleDescription: {
      textAlign: 'left',
    },
  });
}
